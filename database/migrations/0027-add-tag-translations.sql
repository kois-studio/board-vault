-- Tag and tag category names in each interface language (ADR-0024, #184).
-- English stays in Tag.name and TagCategory.name; a language without a row
-- shows the English. The API validates `locale` (es, fr, de, it).
-- The seed below matches the catalogue's tags by their English name, so a
-- name that does not exist inserts nothing.
-- Rollback: DROP TABLE TagTranslation; DROP TABLE TagCategoryTranslation;
-- (every tag goes back to its English name).

CREATE TABLE TagTranslation (
    tagId INTEGER NOT NULL REFERENCES Tag(id) ON DELETE CASCADE,
    locale TEXT NOT NULL,
    name TEXT NOT NULL,
    PRIMARY KEY (tagId, locale)
);

CREATE TABLE TagCategoryTranslation (
    categoryId INTEGER NOT NULL REFERENCES TagCategory(id) ON DELETE CASCADE,
    locale TEXT NOT NULL,
    name TEXT NOT NULL,
    PRIMARY KEY (categoryId, locale)
);

